export function t(key, lang = 'en') {
  const val = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en']?.[key];
  return val || key;
}

export function translateDocument(doc, lang) {
  const els = doc.querySelectorAll('[data-i18n]');
  els.forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.innerHTML = t(key, lang);
  });
  
  const placeholders = doc.querySelectorAll('[data-i18n-placeholder]');
  placeholders.forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', t(key, lang));
  });
  
  const titles = doc.querySelectorAll('[data-i18n-title]');
  titles.forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.setAttribute('title', t(key, lang));
  });
}
